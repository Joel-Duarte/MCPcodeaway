"""Schema-aware onboarding prompt pack and declarative JSON bundle import/apply helpers."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, date, datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from gateway.catalog import ToolCatalog
from gateway.config import GatewaySettings, UpstreamConfig
from gateway.integration_definition import IntegrationDefinition
from gateway.integration_validation import validate_definition_against_catalog
from gateway.upstream_clients import compute_schema_digest, validate_upstream_url


class OnboardingBundle(BaseModel):
    """Declarative onboarding payload generated by an admin's external agent or pasted in UI."""

    model_config = ConfigDict(extra="forbid")

    upstream: dict[str, Any] | None = None
    integration_definition: dict[str, Any] | None = None
    publish: bool = False
    manual_baselines: dict[str, float] = Field(default_factory=dict)


def build_onboarding_prompt_pack(
    *,
    gateway_public_url: str = "http://127.0.0.1:8000",
    upstream_name: str | None = None,
    tools: list[Any] | None = None,
    discovered_candidates: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Build a copyable prompt pack + target JSON schema for an admin's AI agent."""

    tool_catalog_ctx = [
        {
            "qualified_name": t.qualified_name,
            "name": t.name,
            "description": t.description,
            "mutating": t.mutating,
            "schema_sha256": compute_schema_digest([t]),
            "input_schema": t.input_schema,
            "output_schema": t.output_schema,
        }
        for t in (tools or [])
    ]
    bundle_schema = OnboardingBundle.model_json_schema()
    definition_schema = IntegrationDefinition.model_json_schema()

    today = date.today().isoformat()
    context_block = {
        "gateway_apply_endpoint": f"{gateway_public_url.rstrip('/')}/admin/onboarding/bundle/apply",
        "gateway_validate_endpoint": (
            f"{gateway_public_url.rstrip('/')}/admin/onboarding/bundle/validate"
        ),
        "target_upstream_name": upstream_name,
        "effective_from_default": today,
        "discovered_tools": tool_catalog_ctx,
        "auto_discovered_workflow_candidates": [
            c.get("draft_definition", c) for c in (discovered_candidates or [])
        ],
    }

    prompt_text = (
        "You are onboarding a service / API into MCPcodeaway.\n"
        "The user wants to expose this API over MCP with governance, automatic workflow tracking, "
        "and optional interactive MCP App UI widgets.\n\n"
        "Interaction Rules (IMPORTANT):\n"
        "A. Start by inspecting the API details / OpenAPI spec / discovered tools below (or what "
        "the user pastes alongside this prompt).\n"
        "B. BEFORE outputting the final JSON, ask the user concise clarifying questions for "
        "anything unclear — for example:\n"
        "   - Authentication method (delegated OAuth/OBO, API key, user OAuth, or unauthenticated "
        "dev/sandbox) & which roles should access read vs write tools;\n"
        "   - Which endpoints are mutating/destructive and require human confirmation;\n"
        "   - Which proposed business workflows (e.g., X, Y, Z) matter most and roughly how many "
        "minutes a human takes manually (`manual_baseline_minutes`) for each;\n"
        "   - Which lookup/metrics/dashboard endpoints should trigger an interactive MCP App UI.\n"
        "C. Once answered, generate ONE valid JSON object matching the `OnboardingBundle` schema:\n"
        "   1. Populate `upstream` (`name`, `type`: 'openapi' or 'mcp_http', `url`, optional "
        "`openapi_spec_url`, `auth_type`, `allowed_roles`, `mutating_tools`, `tool_effects`, "
        "and `tool_approval_policies` matching each effect: `'none'` for `'read'`, "
        "`'requester_confirmation'` + `confirmation_message` for `'write'`, "
        "`'manager_approval'` + `approver_groups` for `'high_impact'`).\n"
        "   2. Populate `integration_definition` (`manifest_version`: '1.0', `integration`, "
        "`tool_refs` with exact `schema_sha256` from context when available, `workflows`, and "
        "optional `experiences` for MCP Apps UI).\n"
        "   3. For every `workflows[i]`, specify:\n"
        "      - `enabled`: true,\n"
        "      - `participating_tools` (exact `<upstream>__<tool>` names),\n"
        "      - `required_evidence` (RFC 6901 JSON Pointer `result_when` validated against "
        "`output_schema`),\n"
        "      - `completion` (`tool` + `success_when` pointer proving completion),\n"
        "      - `intent_examples` (natural-language user intents that trigger this workflow),\n"
        "      - `business_value` (`manual_baseline_minutes` > 0, `baseline_source`: "
        f"'administrator_estimate', `confidence`: 'unvalidated', `effective_from`: '{today}').\n"
        "   4. For any endpoint needing a visual widget/dashboard card over MCP (`text/html;"
        "profile=mcp-app`), add an `experiences[i]` entry (`ui://mcpcodeaway/<upstream>/<id>/r1`, "
        "`renderer_schema`: 'mcpcodeaway-ui/1', target `tool`, `input_mapping` `/form/<id>`, "
        "`components` using `heading`, `text`, `text_input`, `select`, `button`, `record`). "
        "UI attaches directly to the standard tool (`mca_attr__` wrappers are retired).\n\n"
        f"### Context\n```json\n{json.dumps(context_block, indent=2)}\n```\n\n"
        f"### OnboardingBundle JSON Schema\n```json\n{json.dumps(bundle_schema, indent=2)}\n```\n\n"
        "### IntegrationDefinition JSON Schema\n"
        f"```json\n{json.dumps(definition_schema, indent=2)}\n```"
    )
    return {
        "prompt": prompt_text,
        "upstream_name": upstream_name,
        "tool_count": len(tool_catalog_ctx),
        "candidate_count": len(discovered_candidates or []),
        "validate_endpoint": "/admin/onboarding/bundle/validate",
        "apply_endpoint": "/admin/onboarding/bundle/apply",
        "bundle_schema": bundle_schema,
        "integration_definition_schema": definition_schema,
    }


def validate_onboarding_bundle_payload(
    raw_bundle: dict[str, Any],
    *,
    settings: GatewaySettings,
    catalog: ToolCatalog,
) -> dict[str, Any]:
    """Validate an agent-generated OnboardingBundle without mutating runtime state."""

    bundle = OnboardingBundle.model_validate(raw_bundle)
    if bundle.upstream is None and bundle.integration_definition is None:
        raise ValueError("OnboardingBundle must provide 'upstream' and/or 'integration_definition'")

    validated_upstream: UpstreamConfig | None = None
    if bundle.upstream is not None:
        validated_upstream = UpstreamConfig.model_validate(bundle.upstream)
        for operation, effect in validated_upstream.tool_effects.items():
            policy = validated_upstream.tool_approval_policies.get(operation)
            expected_mode = (
                "none"
                if effect == "read"
                else ("manager_approval" if effect == "high_impact" else "requester_confirmation")
            )
            if (policy.mode if policy else "none") != expected_mode:
                raise ValueError(
                    f"Operation '{operation}' requires the '{expected_mode}' policy "
                    "for its effect classification."
                )
        if validated_upstream.url:
            validate_upstream_url(
                validated_upstream.url,
                app_env=settings.app_env,
                block_private_ips_in_prod=settings.block_private_ips_in_prod,
                allowed_hosts=settings.allowed_upstream_hosts,
            )
        if validated_upstream.openapi_spec_url:
            validate_upstream_url(
                validated_upstream.openapi_spec_url,
                app_env=settings.app_env,
                block_private_ips_in_prod=settings.block_private_ips_in_prod,
                allowed_hosts=settings.allowed_upstream_hosts,
            )
        if validated_upstream.health_check.url:
            validate_upstream_url(
                validated_upstream.health_check.url,
                app_env=settings.app_env,
                block_private_ips_in_prod=settings.block_private_ips_in_prod,
                allowed_hosts=settings.allowed_upstream_hosts,
            )

    validated_def: IntegrationDefinition | None = None
    catalog_checked = False
    warnings: list[str] = []
    if bundle.integration_definition is not None:
        def_payload = json.loads(json.dumps(bundle.integration_definition))
        for wf in def_payload.get("workflows", []):
            wf.setdefault("origin", "agent_prompt")
            wf_id = wf.get("id")
            if isinstance(wf_id, str) and wf_id in bundle.manual_baselines:
                bv = wf.setdefault("business_value", {})
                bv["manual_baseline_minutes"] = bundle.manual_baselines[wf_id]
                bv.setdefault("baseline_source", "administrator_estimate")
                bv.setdefault("confidence", "unvalidated")
                bv.setdefault("effective_from", datetime.now(UTC).date().isoformat())

        upstream_for_def = str(
            (def_payload.get("integration") or {}).get("upstream_name") or ""
        ) or (validated_upstream.name if validated_upstream else "")
        existing_tools = catalog.get_server_tools(upstream_for_def) if upstream_for_def else []
        referenced = {
            t for wf in def_payload.get("workflows", []) for t in wf.get("participating_tools", [])
        } | {e.get("tool") for e in def_payload.get("experiences", []) if e.get("tool")}
        if existing_tools and not def_payload.get("tool_refs"):
            def_payload["tool_refs"] = [
                {"name": tool.qualified_name, "schema_sha256": compute_schema_digest([tool])}
                for tool in existing_tools
                if tool.qualified_name in referenced
            ]
        elif not existing_tools and not def_payload.get("tool_refs") and referenced:
            def_payload["tool_refs"] = [
                {"name": tname, "schema_sha256": "0" * 64} for tname in sorted(referenced)
            ]
        validated_def = IntegrationDefinition.model_validate(def_payload)
        if existing_tools:
            validate_definition_against_catalog(validated_def, catalog)
            catalog_checked = True
            tool_by_name = {t.qualified_name: t for t in existing_tools}
            for wf in validated_def.workflows:
                for ev in wf.required_evidence:
                    t_obj = tool_by_name.get(ev.tool)
                    if ev.result_when is not None and t_obj is not None:
                        props = (t_obj.output_schema or {}).get("properties")
                        if not isinstance(props, dict) or not props:
                            warnings.append(
                                f"Tool '{ev.tool}' has no typed output schema properties for "
                                "result_when predicate verification."
                            )
        else:
            warnings.append(
                f"Upstream '{upstream_for_def}' tools are not yet cached in catalog; "
                "schema hash & output pointer validation will run upon upstream registration."
            )

    digest = (
        hashlib.sha256(
            json.dumps(
                validated_def.model_dump(mode="json"), sort_keys=True, separators=(",", ":")
            ).encode()
        ).hexdigest()
        if validated_def is not None
        else None
    )
    return {
        "valid": True,
        "upstream": validated_upstream.model_dump(mode="json") if validated_upstream else None,
        "integration_definition": (
            validated_def.model_dump(mode="json") if validated_def is not None else None
        ),
        "definition_digest": digest,
        "catalog_checked": catalog_checked,
        "warnings": warnings,
    }
